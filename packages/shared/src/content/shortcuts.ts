const V_WIN = 'Hanya Excel desktop Windows. Tidak berlaku sama di Mac atau Excel untuk web.';

function s(
  slug: string,
  category: ShortcutCategory,
  action: string,
  keysWindows: string | null,
  keysMac: string | null,
  explanation: string,
  example?: string,
  verification: string = keysMac ? V_STD : V_WIN,
): ShortcutDef {
  return { slug, category, action, keysWindows, keysMac, explanation, example, verification };
}


export const person = (r: Rng): string => `${r.pick(FIRST)} ${r.pick(LAST)}`;
/** Daftar nama berbeda-beda (tidak ada yang sama persis). */
export function people(r: Rng, n: number): string[] {
  const seen = new Set<string>();
  while (seen.size < n) seen.add(person(r));
  return [...seen];
}

